<h1>Privacy in this foundation</h1>
<p>
  This local version collects no learner answers or sign-in credentials and runs
  no analytics. Its database checks use synthetic fixtures.
</p>
<p>
  Operational diagnostics contain a random request reference and a safe error
  category. Submitted answers, tokens, cookies and exception messages are
  excluded from those diagnostics.
</p>
<p>
  The full account data policy, provider destinations, export and deletion
  behavior, backup retention and local Anki records need review before pilot
  release.
</p>
