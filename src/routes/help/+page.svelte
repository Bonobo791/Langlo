<h1>Getting started</h1>
<p>
  This version verifies the app foundation. Sign-in and study sessions are not
  available yet.
</p>
<p>
  The full app will keep each learner’s progress private. Lessons and practice
  can run on a phone or computer; approved cards will be delivered from Windows
  when Anki is open and the correct profile is confirmed.
</p>
<p>
  Curriculum review, live provider checks and the Windows connection test must
  be completed before the pilot.
</p>
